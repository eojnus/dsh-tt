// Build and package the same WASM for Host and the client's shared module bundle.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const cargoHome = path.resolve(process.env.CARGO_HOME || path.join(os.homedir(), '.cargo'));
const separator = '\x1f';
const inherited = process.env.CARGO_ENCODED_RUSTFLAGS ??
  process.env.RUSTFLAGS?.trim().split(/\s+/).join(separator);
const rustflags = [
  inherited,
  `--remap-path-prefix=${root}=/dsh-tt`,
  `--remap-path-prefix=${cargoHome}=/cargo`,
].filter(Boolean).join(separator);
const result = spawnSync('cargo', [
  'build', '--locked', '--manifest-path', 'rust/prototype/Cargo.toml',
  '--target', 'wasm32-unknown-unknown', '--release', '--target-dir', 'build/rust-target',
], {
  cwd: root,
  env: { ...process.env, CARGO_ENCODED_RUSTFLAGS: rustflags },
  stdio: 'inherit',
});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

const wasmPath = new URL('../build/rust-target/wasm32-unknown-unknown/release/dsh_tt_prototype.wasm', import.meta.url);
const output = new URL('../plugin/lib/card-assets-wasm-bytes.js', import.meta.url);
const bytes = fs.readFileSync(wasmPath);
const module = new WebAssembly.Module(bytes);
const exports = new Set(WebAssembly.Module.exports(module).map(({ name }) => name));
for (const name of ['memory', 'alloc', 'dealloc', 'normalize_card_text', 'scan_png', 'match_lorebook_keywords',
  'assemble_generation', 'encode_display_capture', 'partition_prompt_injections', 'activate_lorebook',
  'layout_lorebook_buckets', 'build_lorebook_scan_windows', 'plan_main_prompt', 'order_prompt_depth', 'layout_message_fences',
  'project_message_prose', 'normalize_grouped_choices',
  'normalize_preset', 'apply_preset_overrides', 'view_script_preset', 'edit_script_preset',
  'prepare_chat_templates', 'assemble_chat_prompt',
  'project_chat_floors', 'project_live_reply', 'merge_floor_window', 'extension_repository', 'index_extension_archive',
  'parse_extension_commands', 'plan_message_action', 'edit_extension_worldbook']) {
  if (!exports.has(name)) throw new Error(`DSH-TT WASM 缺少接口 ${name}`);
}
fs.writeFileSync(output,
  `// Generated by tools/build-card-assets-wasm.mjs.\nexport const CARD_ASSETS_WASM_BASE64 = "${bytes.toString('base64')}";\n`);
console.log(`已生成 ${fileURLToPath(output)}（WASM ${bytes.length} 字节）`);
